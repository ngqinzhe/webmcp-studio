  it("supports provideTool hosts, string schemas, and native executeTool tests", async () => {
    const harness = createHarness();
    activeHarnesses.push(harness);
    const tools = new Map<string, NativeRegisteredTool>();
    const provideTool = vi.fn((tool: NativeRegisteredTool): boolean => {
      if (typeof tool.inputSchema !== "string") return false;
      tools.set(tool.name, tool);
      return true;
    });
    const executeTool = vi.fn(async (tool: unknown, input: unknown) => {
      if (!tool || typeof tool !== "object") throw new Error("Missing tool.");
      const registered = tools.get((tool as { name: string }).name);
      if (!registered?.execute) throw new Error("Tool is not registered.");
      if (typeof input !== "string") throw new Error("String input required.");
      return registered.execute(JSON.parse(input));
    });
    const host: NativeModelContext = {
      provideTool,
      getTools: () => Array.from(tools.values()),
      executeTool,
    };
    const runtime = new TargetRuntime({
      target,
      document: harness.targetDom.window.document,
      pageWindow: harness.targetWindow,
      parentWindow: harness.parentWindow,
      modelContext: host,
    });
    runtime.addTool(registration("search_products", undefined, querySchema));
    await runtime.start();

    expect(runtime.mode).toBe("native");
    expect(provideTool).toHaveBeenCalledTimes(2);
    expect(typeof provideTool.mock.calls[1]?.[0].inputSchema).toBe("string");
    expect(
      isJsonSchema(
        JSON.parse(provideTool.mock.calls[1]![0].inputSchema as string),
      ),
    ).toBe(true);

    const descriptor = generatedDescriptor();
    await expect(
      runtime.registerGeneratedTool(descriptor),
    ).resolves.toMatchObject({
      registered: true,
      mode: "native",
    });
    const invocation = runtime.testGeneratedTool(
      descriptor.name,
      { query: "keyboard" },
      "native-test-1",
    );
    await settleMessage();
    const call = postedOfType(harness, "generated-tool-call");
    if (typeof call?.requestId !== "string")
      throw new Error("Native test did not reach the generated handler.");
    dispatchFromParent(
      harness,
      generatedResultMessage(descriptor.name, call.requestId, {
        success: true,
        stateChanged: true,
      }),
    );
    await expect(invocation).resolves.toMatchObject({
      success: true,
      stateChanged: true,
    });
    expect(executeTool).toHaveBeenCalledWith(
      expect.objectContaining({ name: descriptor.name }),
      JSON.stringify({ query: "keyboard" }),
    );
  });


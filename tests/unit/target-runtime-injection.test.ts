type NativeRegisteredTool = Parameters<
  NonNullable<NativeModelContext["registerTool"]>
>[0];

interface PostedMessage {
  message: unknown;
  targetOrigin: string;
}

interface RuntimeHarness {
  targetDom: JSDOM;
  parentDom: JSDOM;
  targetWindow: Window;
  parentWindow: Window;
  posts: PostedMessage[];
}

interface NativeHost {
  modelContext: NativeModelContext;
  tools: Map<string, NativeRegisteredTool>;
  registerTool: ReturnType<typeof vi.fn>;
}

